#!/usr/bin/env bun
// ============================================================================
// venue_registry_table.ts — render VENUE_REGISTRY as a table.
//
// Generated from the registry at run time, never retyped, so the document
// cannot disagree with the code it describes.
//
//   bun scripts/venue_registry_table.ts            markdown
//   bun scripts/venue_registry_table.ts --csv      csv
//   bun scripts/venue_registry_table.ts --json     JSON rows
//   bun scripts/venue_registry_table.ts --md docs/venue-registry.md   write
// ============================================================================
import {
  ORIGIN_DOMAIN_REGISTRY,
  VENUE_REGISTRY,
  WRITER_LANE_REGISTRY,
  isTradeableVenue,
  type VenueId,
} from "../lib/domain_venue_registry.ts";

const lanes = Object.keys(WRITER_LANE_REGISTRY) as (keyof typeof WRITER_LANE_REGISTRY)[];
const rows = (Object.keys(VENUE_REGISTRY) as VenueId[]).map((id) => {
  const venue = VENUE_REGISTRY[id];
  const venueLanes = lanes.filter((lane) => WRITER_LANE_REGISTRY[lane].venueId === id);
  return {
    venue: id,
    label: venue.displayLabel,
    kind: venue.kind,
    tradeable: isTradeableVenue(venue),
    settlement: "settlement" in venue ? venue.settlement : "—",
    colour: venue.brandColorHex,
    origins: venue.originDomainIds.join(", "),
    lanes: venueLanes.join(", ") || "(none)",
  };
});

const argv = process.argv.slice(2);
const asCsv = argv.includes("--csv");
const asJson = argv.includes("--json");
const outPath = argv[argv.indexOf("--md") + 1];

function markdown(): string {
  const head = "| Venue | Kind | Tradeable | Settlement | Colour | Origins | Writer lanes |";
  const rule = "|---|---|---|---|---|---|---|";
  const body = rows.map(
    (r) =>
      `| \`${r.venue}\` | ${r.kind} | ${r.tradeable ? "yes" : "**no**"} | ${r.settlement === "—" ? "—" : `\`${r.settlement}\``} | \`${r.colour}\` | ${r.origins.replace(/, /g, ", ")} | ${r.lanes === "(none)" ? "_(none)_" : `\`${r.lanes.split(", ").join("`, `")}\``} |`,
  );
  return [
    "# Venue registry",
    "",
    "Generated by `bun scripts/venue_registry_table.ts` from `lib/domain_venue_registry.ts`.",
    "Origins and colours are derived from `ORIGIN_DOMAIN_REGISTRY`; writer lanes from",
    "`WRITER_LANE_REGISTRY`. Edit those, then re-generate — never this table.",
    "",
    head,
    rule,
    ...body,
    "",
    `venues=${rows.length}  origins=${Object.keys(ORIGIN_DOMAIN_REGISTRY).length}  lanes=${lanes.length}`,
    "",
  ].join("\n");
}

if (asJson) {
  console.log(JSON.stringify({ rows, totals: { venues: rows.length, origins: Object.keys(ORIGIN_DOMAIN_REGISTRY).length, lanes: lanes.length } }, null, 2));
} else if (asCsv) {
  const header = "venue,label,kind,tradeable,settlement,colour,origins,lanes";
  const lines = rows.map((r) =>
    [r.venue, r.label, r.kind, String(r.tradeable), r.settlement, r.colour, `"${r.origins}"`, `"${r.lanes}"`].join(","),
  );
  console.log([header, ...lines].join("\n"));
} else if (outPath) {
  await Bun.write(outPath, markdown());
  console.log(`wrote ${outPath} (${rows.length} venues)`);
} else {
  console.log(markdown());
}
