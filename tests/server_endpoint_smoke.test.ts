import { afterAll, beforeAll, describe, expect, test } from "bun:test";

import { DAEMON_ROUTES } from "../lib/daemon_routes.ts";
import { startServer } from "../services/sportsdesk_webview_server.ts";

/**
 * Live reachability smoke for the daemon route table.
 *
 * `daemon_routes.test.ts` proves the table matches the handler source; this file proves the
 * handler answers at runtime. It asserts the invariants that survive a checkout without the
 * gitignored live captures: no handler 5xx, admin routes reject anonymous callers, and the
 * three shipped POST parsers accept a minimal document.
 *
 * Routes that stream, call an upstream venue, or deliberately fault are skipped; their
 * contracts live in the endpoint-specific suites.
 */

const TOKEN = "endpoint-smoke-token";
const SKIP = new Set([
  "/api/test/error", // deliberately returns 500
  "/api/graph/stream", // SSE: a body is never meant to finish
  "/api/graph-feed", // large feed stream
  "/api/gslive/weblogs", // reads the live GSLive session
  "/api/gslive/session-health", // reads the live GSLive session
  "/api/signals/kalshi", // upstream venue
  "/api/graph/summary", // composes live bridge-relay + Telegram status
  "/api/execution/plan", // reads the live execution/venue plan
  "/tracker", // renders the tracker from live feeds
  "/agent-graph.webp", // raster generated by a separate capture
]);

let server: ReturnType<typeof startServer>;

beforeAll(() => {
  // Bun types the known env keys as readonly; the daemon reads the token per request.
  (Bun.env as Record<string, string | undefined>).SPORTSDESK_ADMIN_TOKEN =
    TOKEN;
  server = startServer({ port: 0, hostname: "127.0.0.1" });
});

afterAll(() => {
  server.stop(true);
});

async function status(
  path: string,
  headers: Record<string, string> = {},
): Promise<number> {
  const response = await fetch(new URL(path, server.url), {
    headers,
    redirect: "manual",
    signal: AbortSignal.timeout(8_000),
  });
  await response.body?.cancel();
  return response.status;
}

describe("daemon endpoint smoke", () => {
  test("every GET/ANY route answers without a handler 5xx", async () => {
    for (const route of DAEMON_ROUTES) {
      if (route.method === "POST" || SKIP.has(route.path)) continue;
      // Live reads default to the live feed (#70): without a session they answer 503 rather
      // than the file. This test is about handler crashes, not data availability.
      const path =
        route.path === "/api/v2/live-bets"
          ? "/api/v2/live-bets?source=file&fallback=strict"
          : /(^|\/)(live-bets|live-wagers)(\/|$)/.test(route.path)
            ? `${route.path}?source=auto`
            : route.path;
      const code = await status(path);
      // An unauthenticated admin route stops at the guard; every other route must reach its
      // handler. 404/410/501 are data states, not crashes, and /health reports HTTP 503 when
      // neither upstream auth plane is configured (#100).
      expect(code, route.path).not.toBe(500);
      if (route.path === "/health") {
        expect([200, 503], route.path).toContain(code);
      } else {
        expect(code, route.path).toBeLessThan(502);
      }
      if (route.guard === "admin") {
        expect(code, route.path).toBe(401);
      }
    }
  }, 30_000);

  test("admin routes accept the bearer after rejecting anonymous", async () => {
    // Once authorized, these handlers call an external service (Telegram API), so an offline
    // checkout cannot answer them. Their anonymous 401 is still covered by the test above; the
    // upstream call itself is pinned by the route's own suite with a mocked transport.
    const UPSTREAM_ON_AUTHORIZED = new Set(["/api/telegram/status"]);
    for (const route of DAEMON_ROUTES) {
      if (route.guard !== "admin" || route.method === "POST") continue;
      expect(await status(route.path), route.path).toBe(401);
      if (UPSTREAM_ON_AUTHORIZED.has(route.path)) continue;
      const authorized = await status(route.path, {
        authorization: `Bearer ${TOKEN}`,
      });
      expect(authorized, route.path).not.toBe(401);
      expect(authorized, route.path).toBeLessThan(500);
    }
  });

  test("XML endpoints decode bytes from the declaration", async () => {
    const encoder = new TextEncoder();
    const iso = new Uint8Array([
      ...encoder.encode(`<?xml version="1.0" encoding="ISO-8859-1"?><a>`),
      0xe9,
      ...encoder.encode("</a>"),
    ]);
    for (const path of [
      "/api/parse-xml",
      "/api/parse-ajax-xml",
      "/api/parse-bet-ticker",
    ]) {
      const response = await fetch(new URL(path, server.url), {
        method: "POST",
        headers: { "content-type": "application/xml" },
        body: iso,
        signal: AbortSignal.timeout(8_000),
      });
      expect(response.status, path).toBe(200);
      expect(await response.json(), path).toEqual({ a: "é" });
    }
  });

  test("the shipped POST parsers accept a minimal document", async () => {
    const cases: ReadonlyArray<[string, string, string]> = [
      ["/api/parse-xml", "<a>1</a>", "application/xml"],
      ["/api/parse-toml", "a = 1\n", "application/toml"],
      ["/api/parse-ajax-xml", '<root><item id="1"/></root>', "application/xml"],
    ];
    for (const [path, body, contentType] of cases) {
      const response = await fetch(new URL(path, server.url), {
        method: "POST",
        headers: { "content-type": contentType },
        body,
        signal: AbortSignal.timeout(8_000),
      });
      await response.body?.cancel();
      expect(response.status, path).toBe(200);
    }
  });

  test("deliberate error probe /api/test/error answers 500 without stack leak", async () => {
    const response = await fetch(new URL("/api/test/error", server.url), {
      signal: AbortSignal.timeout(8_000),
    });
    expect(response.status).toBe(500);
    const body = (await response.json()) as Record<string, unknown>;
    expect(body.success).toBe(false);
    expect(body.error).toBe("Internal Server Error");
    expect(body.stack).toBeUndefined();
  });

  test("specialized data plane routes respond with valid envelopes", async () => {
    const specialized = [
      "/api/graph-feed",
      "/api/gslive/weblogs",
      "/api/gslive/session-health?probe=0",
      "/api/signals/kalshi",
      "/api/graph/summary",
      "/api/execution/plan",
      "/tracker",
    ];
    for (const path of specialized) {
      const response = await fetch(new URL(path, server.url), {
        signal: AbortSignal.timeout(8_000),
      });
      expect(response.status, path).toBeLessThan(500);
      expect(response.status, path).toBe(200);
      await response.body?.cancel();
    }
  });

  test("streaming SSE route /api/graph/stream answers 200 and emits initial summary frame", async () => {
    const response = await fetch(new URL("/api/graph/stream", server.url), {
      signal: AbortSignal.timeout(8_000),
    });
    expect(response.status).toBe(200);
    expect(response.headers.get("content-type")).toContain("text/event-stream");
    const reader = response.body?.getReader();
    expect(reader).toBeDefined();
    if (reader) {
      const { value } = await reader.read();
      const text = new TextDecoder().decode(value);
      expect(text).toContain("event: summary");
      await reader.cancel();
    }
  });

  test("raster route /agent-graph.webp answers without 5xx crash", async () => {
    const response = await fetch(new URL("/agent-graph.webp", server.url), {
      signal: AbortSignal.timeout(8_000),
    });
    // Missing raster is a 404/503 data state, never a 500 handler crash
    expect(response.status).not.toBe(500);
    expect([200, 404, 503]).toContain(response.status);
    await response.body?.cancel();
  });
});
