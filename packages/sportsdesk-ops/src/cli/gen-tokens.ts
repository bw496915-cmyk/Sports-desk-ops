/** Same layout as lib/nsh_frame_schema.ts: channelId4 [28..31], slaTensOfMs8 [20..27], rowIndex20 [0..19]. */
export function packChannelHandle32(channelId4: number, slaTensOfMs8: number, rowIndex20: number): ChannelPackedHandle32 {
  requireInteger(channelId4, "channelId4", 0, 0xf);
  requireInteger(slaTensOfMs8, "slaTensOfMs8", 0, 0xff);
  requireInteger(rowIndex20, "rowIndex20", 0, 0xfffff);
  return ((((channelId4 & 0xf) << 28) | ((slaTensOfMs8 & 0xff) << 20) | (rowIndex20 & 0xfffff)) >>> 0) as ChannelPackedHandle32;
}

