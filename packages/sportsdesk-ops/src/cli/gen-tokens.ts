export class GenTokensError extends Error {
  override readonly name = "GenTokensError";
  constructor(
    readonly code: "ERR_GEN_TOKENS_USAGE" | "ERR_GEN_TOKENS_FORMAT",
    message: string,
  ) {
    super(`${code}: ${message}`);
  }
}

